def export_output(
    output: GeneratedOutput,
    format_type: str,
    include_verification: bool = True,
    include_evaluation: bool = True
) -> tuple[bytes, str, str]:
    """
    Export output to specified format.
    Returns: (content_bytes, filename, media_type)
    """
    format_type = format_type.lower()
    timestamp = datetime.now().strftime('%Y%m%d_%H%M%S')
    base_name = f"ACTP_{output.job.format_type}_{output.model_id.replace('/', '_')}_{timestamp}"

    if format_type == 'pdf':
        content = ExportService.export_to_pdf(output, include_verification, include_evaluation)
        return content, f"{base_name}.pdf", "application/pdf"
    elif format_type == 'docx':
        content = ExportService.export_to_docx(output, include_verification, include_evaluation)
        return content, f"{base_name}.docx", "application/vnd.openxmlformats-officedocument.wordprocessingml.document"
    elif format_type == 'md':
        content = ExportService.export_to_markdown(output, include_verification, include_evaluation).encode('utf-8')
        return content, f"{base_name}.md", "text/markdown"
    elif format_type == 'txt':
        content = ExportService.export_to_txt(output, include_verification, include_evaluation).encode('utf-8')
        return content, f"{base_name}.txt", "text/plain"
    else:
        raise ValueError(f"Unsupported export format: {format_type}")