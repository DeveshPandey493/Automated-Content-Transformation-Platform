def create_test_setup(session):
    """Create a test document, job, and output for testing."""
    doc = Document(
        title="Test Document",
        source_type="PASTED_TEXT",
        file_type="txt",
        total_characters=100,
        total_words=20,
        cleaned_text="This is a test document for export testing.",
    )
    session.add(doc)
    session.flush()

    job = TransformationJob(
        document_id=doc.id,
        format_type="EXECUTIVE_SUMMARY",
        audience="Senior Leadership",
        tone="Formal",
        length_target="MEDIUM",
        status="COMPLETED",
    )
    session.add(job)
    session.flush()

    output = GeneratedOutput(
        job_id=job.id,
        model_id="extractive/textrank",
        model_provider="LOCAL_EXTRACTIVE",
        version=1,
        content="### Executive Summary\n\n**Strategic Overview:**\nThis is a test document.\n\n**Key Findings:**\n- Test finding 1\n- Test finding 2",
        word_count=30,
        generation_latency_ms=100.0,
        input_tokens=50,
        output_tokens=40,
        estimated_cost_usd=0.0,
        generation_params={"target_words": 250, "audience": "Senior Leadership"},
    )
    session.add(output)
    session.flush()

    # Add verification report
    report = VerificationReport(
        output_id=output.id,
        total_claims=3,
        supported_claims=2,
        partially_supported=1,
        unsupported_claims=0,
        contradicted_claims=0,
        factual_consistency_score=0.83,
        summary="Test verification report",
    )
    session.add(report)
    session.flush()

    # Add claims
    claim1 = ExtractedClaim(
        output_id=output.id,
        claim_text="This is a test document.",
        claim_type="GENERAL",
        verification_status="SUPPORTED",
        confidence_score=0.95,
        explanation="Direct match with source.",
    )
    claim2 = ExtractedClaim(
        output_id=output.id,
        claim_text="Test finding 1",
        claim_type="GENERAL",
        verification_status="SUPPORTED",
        confidence_score=0.90,
        explanation="Supported by source.",
    )
    claim3 = ExtractedClaim(
        output_id=output.id,
        claim_text="Test finding 2",
        claim_type="GENERAL",
        verification_status="PARTIALLY_SUPPORTED",
        confidence_score=0.70,
        explanation="Partially supported.",
    )
    session.add_all([claim1, claim2, claim3])
    session.flush()

    # Add evaluation result
    eval_result = EvaluationResult(
        output_id=output.id,
        rouge_1_f1=0.75,
        rouge_2_f1=0.60,
        rouge_l_f1=0.70,
        bert_score_f1=0.72,
        key_fact_coverage=0.8,
        entity_coverage=0.85,
        numerical_coverage=0.9,
        controllability_score=0.95,
        detailed_metrics={},
    )
    session.add(eval_result)
    session.commit()

    return doc, job, output


class TestExportService:
    def test_export_to_pdf(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)
            pdf_bytes = ExportService.export_to_pdf(output)
            assert isinstance(pdf_bytes, bytes)
            assert len(pdf_bytes) > 1000  # PDF should have substantial content
            assert pdf_bytes[:4] == b'%PDF'  # PDF magic bytes
        finally:
            session.close()

    def test_export_to_docx(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)
            docx_bytes = ExportService.export_to_docx(output)
            assert isinstance(docx_bytes, bytes)
            assert len(docx_bytes) > 500
            # DOCX is a zip file
            assert docx_bytes[:4] == b'PK\x03\x04'
        finally:
            session.close()

    def test_export_to_markdown(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)
            md = ExportService.export_to_markdown(output)
            assert isinstance(md, str)
            assert "# Executive Summary" in md
            assert "Generated by:" in md
            assert "Factual Consistency Score" in md
            assert "Claim Details" in md
            assert "Evaluation Metrics" in md
        finally:
            session.close()

    def test_export_to_txt(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)
            txt = ExportService.export_to_txt(output)
            assert isinstance(txt, str)
            # Title is in title case format, not uppercase
            assert "Executive Summary" in txt
            assert "Generated by:" in txt
            assert "FACTUAL VERIFICATION REPORT" in txt
            assert "EVALUATION METRICS" in txt
        finally:
            session.close()

    def test_export_output_function(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            for fmt in ['pdf', 'docx', 'md', 'txt']:
                content, filename, media_type = export_output(output, fmt)
                assert isinstance(content, bytes)
                assert len(content) > 0
                assert filename.endswith(f".{fmt}")
                assert media_type is not None

            # Test invalid format
            with pytest.raises(ValueError):
                export_output(output, 'invalid_format')
        finally:
            session.close()


class TestVersioningService:
    def test_create_new_version(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            new_version = VersioningService.create_new_version(
                db=session,
                original_output=output,
                new_content="Updated content for version 2.",
                editor_notes="Updated key findings",
                user_id="test_user"
            )

            assert new_version.id != output.id
            assert new_version.version == 2
            assert new_version.parent_output_id == output.id
            assert new_version.content == "Updated content for version 2."
            assert new_version.generation_params["edited_from_version"] == 1
            assert new_version.generation_params["editor_notes"] == "Updated key findings"
        finally:
            session.close()

    def test_get_version_history(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            # Create a couple of versions
            v2 = VersioningService.create_new_version(session, output, "Version 2 content", "First edit")
            v3 = VersioningService.create_new_version(session, v2, "Version 3 content", "Second edit")

            history = VersioningService.get_version_history(session, output.id)
            assert len(history) == 3
            assert history[0].version == 1
            assert history[1].version == 2
            assert history[2].version == 3

            # Test getting history from a child version
            history_from_v2 = VersioningService.get_version_history(session, v2.id)
            assert len(history_from_v2) == 3
        finally:
            session.close()

    def test_compare_versions(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            v2 = VersioningService.create_new_version(session, output, "Version 2 content with new info", "First edit")

            comparison = VersioningService.compare_versions(session, output.id, v2.id)
            assert comparison["version_a"]["version"] == 1
            assert comparison["version_b"]["version"] == 2
            assert comparison["word_count_change"] != 0
            assert "diff" in comparison
        finally:
            session.close()


class TestHumanFeedbackService:
    def test_submit_feedback(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            feedback = HumanFeedbackService.submit_feedback(
                db=session,
                output_id=output.id,
                rating_accuracy=5,
                rating_completeness=4,
                rating_readability=5,
                rating_suitability=4,
                reviewer_notes="Great summary, very accurate",
                reviewer_id="reviewer_1"
            )

            assert feedback.output_id == output.id
            assert feedback.rating_accuracy == 5
            assert feedback.rating_completeness == 4
            assert feedback.rating_readability == 5
            assert feedback.rating_suitability == 4
            assert feedback.reviewer_notes == "Great summary, very accurate"
        finally:
            session.close()

    def test_get_feedback_summary(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            # Submit multiple feedback entries
            HumanFeedbackService.submit_feedback(session, output.id, 5, 4, 5, 4, "Good", "r1")
            HumanFeedbackService.submit_feedback(session, output.id, 4, 5, 4, 5, "Excellent", "r2")
            HumanFeedbackService.submit_feedback(session, output.id, 5, 5, 5, 5, "Perfect", "r3")

            summary = HumanFeedbackService.get_feedback_summary(session, output.id)
            assert summary["total_reviews"] == 3
            assert "average_ratings" in summary
            assert summary["average_ratings"]["accuracy"] == 4.67  # (5+4+5)/3
            assert summary["average_ratings"]["overall"] > 0
            assert summary["latest_review"] is not None
            assert len(summary["all_reviews"]) == 3
        finally:
            session.close()

    def test_get_all_feedback_for_job(self):
        SessionLocal = get_session_factory()
        session = SessionLocal()
        try:
            doc, job, output = create_test_setup(session)

            HumanFeedbackService.submit_feedback(session, output.id, 5, 4, 5, 4, "Good", "r1")

            all_feedback = HumanFeedbackService.get_all_feedback_for_job(session, job.id)
            assert len(all_feedback) == 1
            assert all_feedback[0]["output_id"] == output.id
            assert all_feedback[0]["ratings"]["accuracy"] == 5
        finally:
            session.close()